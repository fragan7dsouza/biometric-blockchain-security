h1(doc, 3, "Base Paper and Motivation")

h2(doc, "3.1", "Base Paper Methodology")
para(doc,
     "Sannidhan et al. [1] (“Genetic algorithms and deep learning for unique facial landmark-based key "
     "generation,” Computers and Electrical Engineering, vol. 118, article 109427, 2024) propose a "
     "three-module pipeline. A MobileNetV2 convolutional neural network, trained on 224×224 input images "
     "with the Adam optimizer (learning rate 0.0001), regresses 106 facial landmark coordinates directly "
     "from a face image. The (x, y) coordinates of each landmark are fused into a single scalar via the "
     "Cantor pairing function. A genetic algorithm (population size 100, 1000 generations, two-point "
     "crossover at rate 0.8, random-resetting mutation at rate 0.05, steady-state parent selection) then "
     "optimizes 8 register seed values for an LFSR. The LFSR itself holds 8 registers X0…X7; each "
     "iteration computes a new value from the sum of the even-indexed registers modulo 256, shifts all "
     "registers down by one position, and inserts the new value into X7, using feedback polynomial "
     "x⁷+x⁵+x³+x+1. Iterating this process for each of 74 distinct GA-optimized seed pairs "
     "produced 92,706 total sequences (up to 1287 sequences per seed) across four public face datasets "
     "(LFW [16], FERET [17], Extended Yale Face B [18], CMU Multi-PIE [19]).")

h2(doc, "3.2", "Relevant Characteristics")
para(doc,
     "The base paper reports a Shannon entropy of 3.24 bits for its generated sequence dataset (computed "
     "over the register-value alphabet used by its own LFSR representation, not a byte-level entropy in "
     "the 0–8 bits/byte sense used elsewhere in cryptographic randomness testing), an average Pearson "
     "correlation coefficient of 0.1554 across ten sample sets, and a runs-test Z-statistic of 1.6083. It "
     "compares its total-sequences and Z-statistic figures against three prior LFSR-based systems, including "
     "its own earlier SURF-feature-based system [4].")

h2(doc, "3.3", "Limitations / Opportunities Identified")
