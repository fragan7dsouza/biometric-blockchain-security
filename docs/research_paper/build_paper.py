# 9. SECURITY ANALYSIS
# ======================================================================
h1(doc, 9, "Security Analysis")

h2(doc, "9.1", "Threat Model")
para(doc,
     "The analysis assumes Kerckhoffs's principle: the attacker knows the full algorithm design (GA "
     "configuration, LFSR taps, HKDF parameters, blockchain structure) but not the specific biometric "
     "capture, the derived key, or the plaintext of any given transaction. The attacker may have read access "
     "to the blockchain ledger and to any ciphertext they intercept.")

h2(doc, "9.2", "Confidentiality")
para(doc,
     "Confidentiality of the plaintext rests entirely on the secrecy and quality of the derived AES-256 key, "
     "provided by AES-256-GCM when used correctly (unique nonce per encryption, which this implementation "
     "generates via `os.urandom(12)` by default). AES-GCM provides authenticated encryption when used "
     "correctly; it does not itself compensate for a weak or predictable key.")

h2(doc, "9.3", "Integrity")
para(doc,
     "Blockchain integrity does not provide confidentiality — it provides a tamper-evident commitment to "
     "the ciphertext's hash. An attacker who modifies stored ciphertext without also being able to alter the "
     "corresponding on-chain hash (and, for a longer chain, re-mine every subsequent block's proof-of-work) "
     "will be detected by the verifier. In this local single-process implementation, an attacker with direct "
     "access to the running process's in-memory chain could trivially alter both the ciphertext and the "
     "ledger together; the current design assumes ledger and ciphertext storage are not both fully "
     "compromised by the same attacker, a limitation of the local/simulated deployment rather than of the "
     "PoW/hash-chaining concept itself.")

h2(doc, "9.4", "Biometric Exposure")
para(doc,
     "A face is not inherently secret: it is visible in public, in photographs, and on video. Biometric "
     "features may be reproducible by anyone with access to a sufficiently similar image of the same person. "
     "This system does not attempt to treat the raw face as a secret; it never stores raw landmarks or "
     "images on the blockchain, but the security of key regeneration ultimately depends on an attacker not "
     "being able to obtain a sufficiently accurate capture of the legitimate user's face and reproduce the "
     "same GA/LFSR/HKDF pipeline.")

h2(doc, "9.5", "Key Reproducibility")
para(doc,
     f"Because feature extraction and normalization are sensitive to capture noise, and because no fuzzy "
     f"extractor or error-correcting mechanism is implemented, repeated captures of the same subject do not "
     f"reliably regenerate byte-identical key material — consistent with the measured "
     f"{BS['frr']:.0%} FRR in Section 7.5. This is disclosed as an open problem, not resolved by this "
     f"implementation.")

h2(doc, "9.6", "LFSR Security Considerations")
para(doc,
     "Both LFSR implementations in this codebase are deterministic pseudo-random sequence generators. An "
     "attacker who knows the seed and the tap/feedback configuration (which Kerckhoffs's principle assumes "
     "they do) can reproduce the LFSR output exactly. The LFSR's role in this system is sequence expansion, "
     "not a standalone source of cryptographic unpredictability; the subsequent HKDF step is what "
     "standardizes the final key, not the LFSR itself.")

h2(doc, "9.7", "Cryptographic Key Derivation")
para(doc,
     "HKDF-SHA256 is a key-derivation mechanism, not a biometric stabilizer: given consistent input key "
     "material, it reliably derives a uniform key, but it does not compensate for the input key material "
     "itself differing across captures of the same subject (Section 9.5).")

h2(doc, "9.8", "Blockchain Security Properties")
para(doc,
     "The implemented proof-of-work (difficulty 2, i.e., 2 leading hexadecimal zero characters) is a "
     "demonstration-scale parameter, not a production security parameter; it was not tuned or evaluated "
     "against any specific adversarial mining-power assumption, and no multi-node consensus or "
     "51%-attack-resistance property is claimed for this local, single-process implementation.")

h2(doc, "9.9", "Limitations of Statistical Randomness Testing")
para(doc,
     "Passing Shannon-entropy and runs-test checks provides statistical evidence about a sample's "
     "distributional properties; it does not constitute a proof of cryptographic security or "
     "unpredictability against a computationally bounded adversary, and it does not substitute for formal "
     "cryptanalysis of the key-derivation chain as a whole. The degenerate `Base_Paper_GA_LFSR` runs-test "
     "result described in Section 8.1 is a concrete illustration of how easily such tests can be "
     "misapplied to non-conforming input and produce misleading pass/fail labels if the implementation "
     "detail is not checked.")
